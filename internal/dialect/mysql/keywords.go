package mysql

import (
	"sort"
	"strings"
)

// Keywords returns the SQL keywords offered by completion (spec 9.2):
// the common MySQL/MariaDB set plus the server-specific ones, sorted.
func (m *MySQL) Keywords() []string {
	extra := mysqlOnlyKeywords
	if m.MariaDB {
		extra = mariadbOnlyKeywords
	}
	return merge(commonKeywords, extra)
}

// Functions returns the built-in function names offered by completion.
func (m *MySQL) Functions() []string {
	extra := mysqlOnlyFunctions
	if m.MariaDB {
		extra = mariadbOnlyFunctions
	}
	return merge(commonFunctions, extra)
}

func merge(a, b string) []string {
	seen := map[string]bool{}
	var out []string
	for _, w := range append(strings.Fields(a), strings.Fields(b)...) {
		if !seen[w] {
			seen[w] = true
			out = append(out, w)
		}
	}
	sort.Strings(out)
	return out
}

