package mssql

import (
	"sort"
	"strings"
)

// Keywords returns the T-SQL keywords offered by completion (spec 9.2),
// sorted: the reserved words plus common non-reserved ones.
func (m *MSSQL) Keywords() []string { return words(tsqlKeywords) }

// Functions returns the built-in function names offered by completion.
func (m *MSSQL) Functions() []string { return words(tsqlFunctions) }

func words(s string) []string {
	seen := map[string]bool{}
	var out []string
	for _, w := range strings.Fields(s) {
		if !seen[w] {
			seen[w] = true
			out = append(out, w)
		}
	}
	sort.Strings(out)
	return out
}

