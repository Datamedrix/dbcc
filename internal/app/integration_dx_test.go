// dxServer is a server of a dialect with a schema level.
type dxServer struct {
	name, driver, addr, user, pwEnv, params string
	schema                                  string // default schema
	adminDB                                 string // database to connect to for CREATE/DROP DATABASE
	ddl                                     string
}

const pgSchema = `CREATE TABLE parent (a integer NOT NULL, b varchar(10) NOT NULL, label text, PRIMARY KEY (a, b));
CREATE TABLE items (
  id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code   varchar(10) NOT NULL CONSTRAINT uq_items_code UNIQUE,
  name   text,
  price  numeric(10,2) NOT NULL DEFAULT 0 CONSTRAINT chk_price CHECK (price >= 0),
  qty    integer NOT NULL DEFAULT 1,
  total  numeric(12,2) GENERATED ALWAYS AS (price * qty) STORED,
  parent_a integer, parent_b varchar(10),
  CONSTRAINT fk_items_parent FOREIGN KEY (parent_a, parent_b) REFERENCES parent (a, b)
);
CREATE INDEX ix_items_name ON items (name) INCLUDE (qty) WHERE qty > 0;
CREATE VIEW v_items AS SELECT id, code, qty FROM items;
CREATE MATERIALIZED VIEW mv_codes AS SELECT code FROM items;
CREATE FUNCTION f_double(x integer) RETURNS integer LANGUAGE sql AS $$ SELECT x * 2 $$;
CREATE PROCEDURE p_count(INOUT n bigint DEFAULT NULL) LANGUAGE plpgsql AS $$
BEGIN
  -- count items in stock
  SELECT count(*) INTO n FROM items WHERE qty > 0;
END
$$;
CREATE SCHEMA other;
CREATE TABLE other.t (id integer PRIMARY KEY);
CREATE TABLE txn (id integer PRIMARY KEY);
`

const msSchema = `CREATE TABLE parent (a int NOT NULL, b varchar(10) NOT NULL, label nvarchar(50),
  CONSTRAINT PK_parent PRIMARY KEY (a, b));
CREATE TABLE items (
  id     int IDENTITY(1,1) CONSTRAINT PK_items PRIMARY KEY,
  code   varchar(10) NOT NULL CONSTRAINT UQ_items_code UNIQUE,
  name   nvarchar(50),
  price  decimal(10,2) NOT NULL CONSTRAINT DF_items_price DEFAULT 0 CONSTRAINT CK_items_price CHECK (price >= 0),
  qty    int NOT NULL CONSTRAINT DF_items_qty DEFAULT 1,
  total  AS (price * qty) PERSISTED,
  parent_a int, parent_b varchar(10),
  CONSTRAINT FK_items_parent FOREIGN KEY (parent_a, parent_b) REFERENCES parent (a, b)
);
CREATE INDEX IX_items_name ON items (name) INCLUDE (qty) WHERE qty > 0;
CREATE TABLE txn (id int PRIMARY KEY);
GO
CREATE VIEW v_items AS SELECT id, code, qty FROM dbo.items;
GO
CREATE FUNCTION f_double(@x int) RETURNS int AS BEGIN RETURN @x * 2 END;
GO
CREATE PROCEDURE p_count AS
  -- count items in stock
  SELECT COUNT(*) AS n FROM dbo.items WHERE qty > 0;
GO
CREATE SCHEMA other;
GO
CREATE TABLE other.t (id int PRIMARY KEY);
`

const dxData = `INSERT INTO parent (a, b, label) VALUES (1, 'x', 'one'), (2, 'y', NULL);
INSERT INTO items (code, name, price, qty, parent_a, parent_b) VALUES
  ('A1', 'Alpha', 2.50, 4, 1, 'x'), ('B2', 'Beta', 10.00, 1, 2, 'y'), ('C3', 'Gamma', 1.25, 8, NULL, NULL);
`

func dxServers(t *testing.T) []dxServer {
	var out []dxServer
	if a := os.Getenv("DBCC_IT_POSTGRES"); a != "" {
		out = append(out, dxServer{name: "postgres", driver: "postgres", addr: a, user: "postgres", pwEnv: "DBCC_IT_PG_PW",
			params: `sslmode = "disable"`, schema: "public", adminDB: "postgres", ddl: pgSchema})
	}
	if a := os.Getenv("DBCC_IT_MSSQL"); a != "" {
		out = append(out, dxServer{name: "mssql", driver: "mssql", addr: a, user: "sa", pwEnv: "DBCC_IT_MSSQL_PW",
			params: `TrustServerCertificate = "true"`, schema: "dbo", adminDB: "master", ddl: msSchema})
	}
	if len(out) == 0 {
		t.Skip("no DBCC_IT_POSTGRES / DBCC_IT_MSSQL servers configured")
	}
	return out
}

// dxConfig writes profiles "it" and "it2" for the server and database db,
// with extra lines appended to profile "it".
func dxConfig(t *testing.T, s dxServer, db, extra string) *config.Config {
	t.Helper()
	host, port, _ := net.SplitHostPort(s.addr)
	prof := func(name, more string) string {
		return fmt.Sprintf("[profiles.%s]\ndriver = %q\nhost = %q\nport = %s\nuser = %q\ndatabase = %q\npassword = \"env:%s\"\nparams = { %s }\n%s\n",
			name, s.driver, host, port, s.user, db, s.pwEnv, s.params, more)
	}
	path := filepath.Join(t.TempDir(), "config.toml")
	if err := os.WriteFile(path, []byte(prof("it", extra)+prof("it2", "")), 0o600); err != nil {
		t.Fatal(err)
	}
	cfg, err := config.Load(path)
	if err != nil {
		t.Fatal(err)
	}
	return cfg
}

func (s dxServer) dropSQL(db string) string {
	if s.driver == "postgres" {
		return "DROP DATABASE IF EXISTS " + db + " WITH (FORCE)"
	}
	return "IF DB_ID('" + db + "') IS NOT NULL BEGIN ALTER DATABASE " + db +
		" SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE " + db + " END"
}

// dxSetup creates dxDB with the dialect's schema and data and returns a
// config whose profiles start in it.
func dxSetup(t *testing.T, s dxServer) *config.Config {
	t.Helper()
	t.Setenv("XDG_CONFIG_HOME", t.TempDir()) // no user commands
	admin := dxConfig(t, s, s.adminDB, "")
	// SQL Server may still be starting after a container restart.
	deadline := time.Now().Add(90 * time.Second)
	for {
		_, stderr, code := run(t, admin, Options{Command: s.dropSQL(dxDB)}, "")
		if code == 0 {
			break
		}
		if time.Now().After(deadline) {
			t.Fatalf("drop: %s", stderr)
		}
		time.Sleep(3 * time.Second)
	}
	if _, stderr, code := run(t, admin, Options{Command: "CREATE DATABASE " + dxDB}, ""); code != 0 {
		t.Fatalf("create: %s", stderr)
	}
	t.Cleanup(func() { run(t, admin, Options{Command: s.dropSQL(dxDB)}, "") })
	cfg := dxConfig(t, s, dxDB, "")
	for _, src := range []string{s.ddl, dxData} {
		if _, stderr, code := run(t, cfg, Options{}, src); code != 0 {
			t.Fatalf("schema: %s", stderr)
		}
	}
	return cfg
}

// dxHeadless is one headless command layer for several command lines.
type dxHeadless struct {
	t        *testing.T
	h        *headless
	out, err *bytes.Buffer
	ctx      context.Context
	dispatch func(line string) error
}

func newDX(t *testing.T, cfg *config.Config, yes bool) *dxHeadless {
	t.Helper()
	var out, errb bytes.Buffer
	env := &Env{Opts: &Options{Profile: "it", Format: "csv", Yes: yes}, Config: cfg, Stdout: &out, Stderr: &errb}
	h := newHeadless(env)
	t.Cleanup(h.ws.CloseAll)
	ctx := context.Background()
	if _, err := h.ws.Chdir(ctx, "/it"); err != nil {
		t.Fatal(err)
	}
	reg, err := h.registry()
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(reg.Runtime().Close)
	return &dxHeadless{t: t, h: h, out: &out, err: &errb, ctx: ctx, dispatch: func(l string) error { return reg.Dispatch(ctx, l) }}
}

// do runs a line and returns its stdout.
func (x *dxHeadless) do(line string) string {
	x.t.Helper()
	x.out.Reset()
	if err := x.dispatch(line); err != nil {
		x.t.Fatalf("%s: %v", line, err)
	}
	return x.out.String()
}

func wantAll(t *testing.T, what, out string, wants ...string) {
	t.Helper()
	for _, w := range wants {
		if !strings.Contains(out, w) {
			t.Errorf("%s lacks %q:\n%s", what, w, out)
		}
	}
}

func TestDXDataAndNavigation(t *testing.T) {
	for _, s := range dxServers(t) {
		t.Run(s.name, func(t *testing.T) {
			cfg := dxSetup(t, s)
			for _, c := range []struct {
				cmd   string
				lines int
				want  string
			}{
				{"ll items", 4, "id,code,name,price,qty,total,parent_a,parent_b"},
				{"ll /it/" + dxDB + "/" + s.schema + "/items", 4, "B2,Beta"},
				{"ll " + s.schema + ".items", 4, "C3,Gamma"},
				{"ll " + dxDB + "." + s.schema + ".parent", 3, "2,y,\n"},
				{"ll v_items", 4, "id,code,qty"},
				{"head items 2", 3, "A1"},
				{"head items 0", 1, "id,code"},
				{"wc items", 2, "rows,object\n3,items"},
				{"wc /it/" + dxDB + "/" + s.schema + "/v_items", 2, "3,v_items"},
			} {
				out, stderr, code := run(t, cfg, Options{Command: c.cmd, Format: "csv"}, "")
				if code != 0 {
					t.Errorf("%s: exit %d: %s", c.cmd, code, stderr)
					continue
				}
				if n := len(csvLines(out)); n != c.lines || !strings.Contains(out, c.want) {
					t.Errorf("%s: %d lines (want %d), want %q in:\n%s", c.cmd, n, c.lines, c.want, out)
				}
			}
			if s.driver == "postgres" {
				if out := must(t, cfg, Options{Command: "ll mv_codes", Format: "csv"}); len(csvLines(out)) != 1 {
					t.Errorf("ll mv_codes (not refreshed: no rows):\n%s", out)
				}
			}
			out := must(t, cfg, Options{Command: "ls", Format: "csv"})
			wantAll(t, "ls", out, "items,table,", "v_items,view,", "f_double,function,", "p_count,procedure,")
			out = must(t, cfg, Options{Command: "ls ..", Format: "csv"})
			wantAll(t, "ls ..", out, s.schema+",schema,", "other,schema,")
			out = must(t, cfg, Options{Command: "ls /it", Format: "csv"})
			wantAll(t, "ls /it", out, dxDB+",database,")
			out = must(t, cfg, Options{Command: "ls /", Format: "csv"})
			wantAll(t, "ls /", out, "it,connection,"+s.driver+" ", "(current)")
			if out := strings.TrimSpace(must(t, cfg, Options{Command: "pwd"})); out != "/it/"+dxDB+"/"+s.schema {
				t.Errorf("pwd: %q", out)
			}
			if _, stderr, code := run(t, cfg, Options{Command: "ll nosuch"}, ""); code != ExitSQL || !strings.Contains(stderr, "no such object") {
				t.Errorf("ll nosuch: %d %q", code, stderr)
			}

			// cd through one command layer.
			x := newDX(t, cfg, false)
			pwd := func(want string) {
				t.Helper()
				if got := strings.TrimSpace(x.do("pwd")); got != want {
					t.Errorf("pwd = %q, want %q", got, want)
				}
			}
			base := "/it/" + dxDB
			pwd(base + "/" + s.schema)
			x.do("cd other") // sibling schema (leniency in cd.lua)
			pwd(base + "/other")
			if out := x.do("ll t"); len(csvLines(out)) != 1 {
				t.Errorf("ll t in other: %q", out)
			}
			x.do("cd " + s.schema)
			pwd(base + "/" + s.schema)
			x.do("cd ..")
			pwd(base)
			x.do("cd other") // child schema
			pwd(base + "/other")
			x.do("cd " + s.adminDB) // sibling database (reconnect on PostgreSQL)
			if got := strings.TrimSpace(x.do("pwd")); !strings.HasPrefix(got, "/it/"+s.adminDB+"/") {
				t.Errorf("cd to sibling database: pwd %q", got)
			}
			if db := x.h.ws.Current().Database(); db != s.adminDB {
				t.Errorf("session database %q", db)
			}
			x.do("cd -")
			pwd(base + "/other")
			x.do("cd /it/" + dxDB + "/" + s.schema)
			pwd(base + "/" + s.schema)
			if err := x.dispatch("cd nosuchthing"); err == nil || !strings.HasPrefix(err.Error(), "cd: ") {
				t.Errorf("cd nosuchthing: %v", err)
			}
			pwd(base + "/" + s.schema)
			// Objects of another database on PostgreSQL go through their own
			// auxiliary connection.
			x.do("cd /it/" + s.adminDB)
			if out := x.do("ls /it/" + dxDB + "/" + s.schema); !strings.Contains(out, "items,table") {
				t.Errorf("ls of another database:\n%s", out)
			}
		})
	}
}

func TestDXCatEdit(t *testing.T) {
	for _, s := range dxServers(t) {
		t.Run(s.name, func(t *testing.T) {
			cfg := dxSetup(t, s)
			out := must(t, cfg, Options{Command: "cat items"})
			ix := "ix_items_name"
			if s.driver == "mssql" {
				ix = "IX_items_name"
			}
			wantAll(t, "cat items", out, "Columns\n", "Primary and unique keys\n", "Foreign keys\n", "Check constraints\n",
				"Indexes\n", "Triggers\n", "Table options\n", "| Include", "| Filter", ix, "| qty ", "parent_a, parent_b")
			if strings.Contains(out, "\x1b[") {
				t.Errorf("colour codes in headless output")
			}
			idx := section(out, "Indexes")
			if !strings.Contains(idx, "qty") || !strings.Contains(idx, "> 0") && !strings.Contains(idx, ">(0)") {
				t.Errorf("index include/filter:\n%s", idx)
			}
			opts := section(out, "Table options")
			if strings.Contains(opts, "identity") || strings.Contains(opts, "include") {
				t.Errorf("identity/include left in the options:\n%s", opts)
			}
			if s.driver == "postgres" {
				wantAll(t, "cat items", section(out, "Columns"), "GENERATED BY DEFAULT AS IDENTITY", "GENERATED ALWAYS AS", "STORED")
				mv := must(t, cfg, Options{Command: "cat mv_codes"})
				wantAll(t, "cat mv_codes", mv, "Columns\n", "Indexes\n", "Definition\n", "SELECT")
			} else {
				wantAll(t, "cat items", section(out, "Columns"), "IDENTITY(1,1)", "GENERATED ALWAYS AS ([price]*[qty]) STORED")
			}
			wantAll(t, "cat v_items", must(t, cfg, Options{Command: "cat v_items"}), "SELECT", "items")
			wantAll(t, "cat f_double", must(t, cfg, Options{Command: "cat f_double"}), "f_double", "2")
			wantAll(t, "cat p_count", must(t, cfg, Options{Command: "cat -t procedure p_count"}), "p_count", "count items in stock")

			// edit prints a replace script that runs unchanged.
			script := must(t, cfg, Options{Command: "edit p_count"})
			changed := strings.Replace(script, "count items in stock", "count items on hand", 1)
			if changed == script {
				t.Fatalf("edit p_count:\n%s", script)
			}
			if _, stderr, code := run(t, cfg, Options{}, changed); code != 0 {
				t.Fatalf("running the replace script: %s\n%s", stderr, changed)
			}
			wantAll(t, "replaced p_count", must(t, cfg, Options{Command: "cat p_count"}), "count items on hand")
			for _, cmd := range []string{"edit v_items", "edit f_double"} {
				script := must(t, cfg, Options{Command: cmd})
				if !strings.Contains(script, "CREATE") {
					t.Errorf("%s:\n%s", cmd, script)
				}
				if _, stderr, code := run(t, cfg, Options{}, script); code != 0 {
					t.Errorf("%s script: %s", cmd, stderr)
				}
			}
			if _, stderr, code := run(t, cfg, Options{Command: "edit items"}, ""); code != ExitSQL || !strings.Contains(stderr, "no such object") {
				t.Errorf("edit table: %d %q", code, stderr)
			}
		})
	}
}

func TestDXCpMv(t *testing.T) {
	for _, s := range dxServers(t) {
		t.Run(s.name, func(t *testing.T) {
			cfg := dxSetup(t, s)
			if _, stderr, code := run(t, cfg, Options{Command: "cp items items_d"}, ""); code != ExitSQL || !strings.Contains(stderr, "confirmation required") {
				t.Errorf("cp without --yes: %d %q", code, stderr)
			}
			if _, stderr, code := run(t, cfg, Options{Command: "cp items items_d", Yes: true}, ""); code != 0 || !strings.Contains(stderr, "(3 rows)") {
				t.Fatalf("cp: %d %q", code, stderr)
			}
			if out := must(t, cfg, Options{Command: "wc items_d", Format: "csv"}); !strings.Contains(out, "3,items_d") {
				t.Errorf("cp data: %q", out)
			}
			if _, stderr, code := run(t, cfg, Options{Command: "cp -a items items_a", Yes: true}, ""); code != 0 || !strings.Contains(stderr, "(3 rows)") {
				t.Fatalf("cp -a: %d %q", code, stderr)
			}
			cp := must(t, cfg, Options{Command: "cat items_a"})
			if strings.Contains(section(cp, "Primary and unique keys"), "(none)") || strings.Contains(section(cp, "Indexes"), "(none)") ||
				!strings.Contains(section(cp, "Check constraints"), "price") {
				t.Errorf("cp -a lost keys, indexes or checks:\n%s", cp)
			}
			if !strings.Contains(section(cp, "Foreign keys"), "(none)") {
				t.Errorf("cp -a copied foreign keys:\n%s", cp)
			}
			q := "SELECT id, code, total FROM %s ORDER BY id"
			a := must(t, cfg, Options{Command: fmt.Sprintf(q, "items"), Format: "csv"})
			b := must(t, cfg, Options{Command: fmt.Sprintf(q, "items_a"), Format: "csv"})
			if a != b || !strings.Contains(a, "10.00") {
				t.Errorf("cp -a data (identity values kept, generated columns recomputed):\n%s\n%s", a, b)
			}
			// The identity continues after the copied values.
			must(t, cfg, Options{Command: "INSERT INTO items_a (code) VALUES ('D4')"})
			must(t, cfg, Options{Command: "cp -a v_items v_copy", Yes: true})
			if out := must(t, cfg, Options{Command: "ll v_copy", Format: "csv"}); len(csvLines(out)) != 4 {
				t.Errorf("view copy: %q", out)
			}

			if _, stderr, code := run(t, cfg, Options{Command: "mv items_d items_e"}, ""); code != ExitSQL || !strings.Contains(stderr, "items_e") {
				t.Errorf("mv without --yes: %d %q", code, stderr)
			}
			must(t, cfg, Options{Command: "mv items_d items_e", Yes: true})
			must(t, cfg, Options{Command: "mv v_copy v_moved", Yes: true})
			out := must(t, cfg, Options{Command: "ls", Format: "csv"})
			if !strings.Contains(out, "items_e,table") || strings.Contains(out, "items_d,") || !strings.Contains(out, "v_moved,view") {
				t.Errorf("after mv:\n%s", out)
			}
			if out := must(t, cfg, Options{Command: "wc items_e", Format: "csv"}); !strings.Contains(out, "3,items_e") {
				t.Errorf("renamed table: %q", out)
			}
			for _, c := range []string{"mv p_count p2", "mv items_e other.x", "mv nosuch x"} {
				if _, _, code := run(t, cfg, Options{Command: c, Yes: true}, ""); code != ExitSQL {
					t.Errorf("%s: exit %d", c, code)
				}
			}
			ro := dxConfig(t, s, dxDB, "read_only = true")
			if _, stderr, code := run(t, ro, Options{Command: "cp items items_ro", Yes: true}, ""); code != ExitSQL || !strings.Contains(stderr, "read-only") {
				t.Errorf("cp read-only: %d %q", code, stderr)
			}
		})
	}
}

