// anyServer is a server of any dialect for runner-level tests.
type anyServer struct {
	name string
	cfg  func(t *testing.T, db, extra string) *config.Config
	db   string
}

// allServers returns every configured server with a database in which
// table txn (id int primary key) exists, created fresh.
func allServers(t *testing.T) []anyServer {
	var out []anyServer
	for _, s := range []server{{"mysql", os.Getenv("DBCC_IT_MYSQL")}, {"mariadb", os.Getenv("DBCC_IT_MARIADB")}} {
		if s.addr == "" {
			continue
		}
		s := s
		out = append(out, anyServer{name: s.name, db: "dbcc_it_txn", cfg: func(t *testing.T, db, extra string) *config.Config {
			return multiConfigDB(t, s, db, extra)
		}})
	}
	if os.Getenv("DBCC_IT_POSTGRES") != "" || os.Getenv("DBCC_IT_MSSQL") != "" {
		for _, s := range dxServers(t) {
			s := s
			out = append(out, anyServer{name: s.name, db: dxDB, cfg: func(t *testing.T, db, extra string) *config.Config {
				return dxConfig(t, s, db, extra)
			}})
		}
	}
	if len(out) == 0 {
		t.Skip("no DBCC_IT_* servers configured")
	}
	return out
}

// prepare creates the test database of s (MySQL: dbcc_it_txn with table
// txn; others: the dx schema, which has txn).
func (a anyServer) prepare(t *testing.T) {
	t.Helper()
	switch a.name {
	case "postgres", "mssql":
		for _, s := range dxServers(t) {
			if s.name == a.name {
				dxSetup(t, s)
			}
		}
	default:
		cfg := setupDB(t, server{a.name, addrOf(a.name)}, a.db)
		if _, stderr, code := run(t, cfg, Options{Command: "CREATE TABLE txn (id INT PRIMARY KEY)"}, ""); code != 0 {
			t.Fatal(stderr)
		}
	}
}

func addrOf(name string) string {
	if name == "mariadb" {
		return os.Getenv("DBCC_IT_MARIADB")
	}
	return os.Getenv("DBCC_IT_MYSQL")
}

type countSink struct {
	results []*exec.Result
	msgs    []exec.Message
}

func (c *countSink) Result(r *exec.Result)  { c.results = append(c.results, r) }
func (c *countSink) Message(m exec.Message) { c.msgs = append(c.msgs, m) }

func openIt(t *testing.T, cfg *config.Config, name string) *session.Session {
	t.Helper()
	ws := session.NewWorkspace(cfg, nil)
	t.Cleanup(ws.CloseAll)
	s, err := ws.Open(context.Background(), name)
	if err != nil {
		t.Fatal(err)
	}
	return s
}

func count(t *testing.T, s *session.Session) int {
	t.Helper()
	var n int
	if err := s.Main().QueryRowContext(context.Background(), "SELECT COUNT(*) FROM txn").Scan(&n); err != nil {
		t.Fatal(err)
	}
	return n
}

func TestManualTransactions(t *testing.T) {
	for _, a := range allServers(t) {
		t.Run(a.name, func(t *testing.T) {
			a.prepare(t)
			cfg := a.cfg(t, a.db, "autocommit = false")
			ctx := context.Background()
			s := openIt(t, cfg, "it")
			other := openIt(t, a.cfg(t, a.db, ""), "it2")
			sink := &countSink{}
			r := exec.NewRunner(s, sink)
			step := func(src string, wantOpen bool) {
				t.Helper()
				if err := r.RunScript(ctx, src, 0); err != nil {
					t.Fatalf("%s: %v", src, err)
				}
				if got := s.TxnOpen(); got != wantOpen {
					t.Errorf("after %q: TxnOpen = %v, want %v", src, got, wantOpen)
				}
			}
			step("INSERT INTO txn VALUES (1)", true)
			step("ROLLBACK", false)
			if n := count(t, other); n != 0 {
				t.Errorf("rollback did not undo the insert: %d rows", n)
			}
			step("INSERT INTO txn VALUES (2)", true)
			step("SELECT COUNT(*) FROM txn", true)
			step("COMMIT", false)
			if n := count(t, other); n != 1 {
				t.Errorf("commit: %d rows", n)
			}
			// One batch with the commit (one statement on MSSQL, two on the others).
			step("INSERT INTO txn VALUES (3); COMMIT", false)
			if n := count(t, other); n != 2 {
				t.Errorf("batch commit: %d rows", n)
			}
			// ctx:exec-style statements (forms, write commands) join the transaction.
			if _, err := r.Exec(ctx, "INSERT INTO txn VALUES (4)"); err != nil {
				t.Fatal(err)
			}
			if !s.TxnOpen() {
				t.Errorf("Exec did not open the transaction")
			}
			step("ROLLBACK", false)
			if n := count(t, other); n != 2 {
				t.Errorf("rollback after Exec: %d rows", n)
			}
			// A failing statement inside the transaction: it stays open
			// (PostgreSQL: aborted, only ROLLBACK is accepted).
			step("INSERT INTO txn VALUES (5)", true)
			if err := r.RunScript(ctx, "INSERT INTO txn VALUES (5)", 0); err == nil {
				t.Errorf("duplicate key accepted")
			}
			if a.name != "mssql" && !s.TxnOpen() {
				// SQL Server keeps the transaction unless XACT_ABORT is on.
				t.Errorf("failed statement closed the transaction state")
			}
			step("ROLLBACK", false)
			if n := count(t, other); n != 2 {
				t.Errorf("rollback after error: %d rows", n)
			}
		})
	}
}

func TestMultipleResultSets(t *testing.T) {
	for _, a := range allServers(t) {
		t.Run(a.name, func(t *testing.T) {
			a.prepare(t)
			s := openIt(t, a.cfg(t, a.db, ""), "it")
			sink := &countSink{}
			r := exec.NewRunner(s, sink)
			ctx := context.Background()
			var src string
			want := 2
			switch a.name {
			case "mssql":
				src = "SELECT 1 AS a; SELECT 2 AS b, 3 AS c"
			case "postgres":
				src = "SELECT 1 AS a; SELECT 2 AS b, 3 AS c" // two statements
			default:
				src = "DELIMITER $$\nCREATE PROCEDURE p2() BEGIN SELECT 1 AS a; SELECT 2 AS b, 3 AS c; END$$\nDELIMITER ;\n"
				if err := r.RunScript(ctx, src, 0); err != nil {
					t.Fatal(err)
				}
				sink.results = nil
				src = "CALL p2()"
			}
			if err := r.RunScript(ctx, src, 0); err != nil {
				t.Fatal(err)
			}
			if len(sink.results) != want {
				t.Fatalf("%d result tabs, want %d", len(sink.results), want)
			}
			if c := sink.results[1].Columns; len(c) != 2 || c[0].Name != "b" {
				t.Errorf("second result columns %+v", c)
			}
			// A single result stays lazily loaded.
			sink.results = nil
			r.FetchSize = 1
			if err := r.RunScript(ctx, "SELECT 1 AS x UNION ALL SELECT 2 UNION ALL SELECT 3", 0); err != nil {
				t.Fatal(err)
			}
			if len(sink.results) != 1 || !sink.results[0].More() {
				t.Errorf("single result not lazy: %d results", len(sink.results))
			}
			s.CloseCursor()
		})
	}
}

