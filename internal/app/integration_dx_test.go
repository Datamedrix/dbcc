func TestDXKill(t *testing.T) {
	for _, s := range dxServers(t) {
		t.Run(s.name, func(t *testing.T) {
			cfg := dxSetup(t, s)
			x := newDX(t, cfg, true)
			idSQL := "SELECT pg_backend_pid()"
			if s.driver == "mssql" {
				idSQL = "SELECT @@SPID"
			}
			victim, err := x.h.ws.Open(x.ctx, "it2")
			if err != nil {
				t.Fatal(err)
			}
			var id, me int
			if err := victim.Main().QueryRowContext(x.ctx, idSQL).Scan(&id); err != nil {
				t.Fatal(err)
			}
			x.h.ws.Current().Main().QueryRowContext(x.ctx, idSQL).Scan(&me)
			if err := x.dispatch("kill " + strconv.Itoa(me)); err == nil || !strings.Contains(err.Error(), "is this session") {
				t.Errorf("kill own session: %v", err)
			}
			if s.driver == "postgres" {
				if err := x.dispatch("kill -q " + strconv.Itoa(id)); err != nil {
					t.Fatalf("kill -q: %v", err)
				}
				if err := victim.Main().PingContext(x.ctx); err != nil {
					t.Errorf("kill -q terminated the session: %v", err)
				}
				if err := x.dispatch("kill 999999"); err == nil || !strings.Contains(err.Error(), "no session") {
					t.Errorf("kill unknown: %v", err)
				}
			} else if err := x.dispatch("kill -q " + strconv.Itoa(id)); err == nil || !strings.Contains(err.Error(), "cannot cancel") {
				t.Errorf("kill -q on mssql: %v", err)
			}
			x.err.Reset()
			if err := x.dispatch("kill " + strconv.Itoa(id)); err != nil {
				t.Fatalf("kill: %v", err)
			}
			if !strings.Contains(x.err.String(), "kill: session "+strconv.Itoa(id)+" terminated") {
				t.Errorf("kill message: %q", x.err.String())
			}
			var one int
			deadline := time.Now().Add(5 * time.Second)
			for victim.Main().QueryRowContext(x.ctx, "SELECT 1").Scan(&one) == nil {
				if time.Now().After(deadline) {
					t.Errorf("killed session still answers")
					break
				}
				time.Sleep(100 * time.Millisecond)
			}
		})
	}
	for _, s := range dxServers(t) {
		cfg := dxConfig(t, s, s.adminDB, "")
		want := "KILL 999999999"
		if s.driver == "postgres" {
			want = "no session 999999999"
		}
		if _, stderr, code := run(t, cfg, Options{Command: "kill 999999999"}, ""); code != ExitSQL || !strings.Contains(stderr, want) {
			t.Errorf("%s: kill without --yes: %d %q", s.name, code, stderr)
		}
	}
}

